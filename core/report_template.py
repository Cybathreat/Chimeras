def render_report(
    engagement_name: str = "N/A",
    client_name: str = "",
    executive_summary: str = "",
    mission_scope: str = "",
    internal_scope: str = "",
    roe: str = "",
    targets: Optional[List[str]] = None,
    findings: Optional[List[Dict[str, Any]]] = None,
    engagement_flow: str = "",
    critical_findings: Optional[List[Dict]] = None,
    decision_audit: str = "",
    cleanup_status: str = "No cleanup performed.",
    mission_outcome: str = "",
) -> str:
    """Render the pentest report from structured data.

    Args:
        findings: List of dicts with keys: id, title, severity, cvss,
                  status, description, risks, attack_vectors, poc,
                  proof_of_existence, remediation.

    Returns:
        Complete markdown report string.
    """
    targets = targets or []
    findings = findings or []
    critical_findings = critical_findings or []

    context = {
        "engagement_name": engagement_name,
        "client_name": client_name,
        "report_date": datetime.utcnow().strftime("%Y-%m-%d"),
        "executive_summary": executive_summary or "N/A",
        "mission_scope": mission_scope or "N/A",
        "internal_scope": internal_scope,
        "roe": roe,
        "targets": targets,
        "findings": findings,
        "engagement_flow": engagement_flow or "N/A",
        "critical_findings": critical_findings,
        "decision_audit": decision_audit or "N/A",
        "cleanup_status": cleanup_status,
        "mission_outcome": mission_outcome or "N/A",
        "generated_at": datetime.utcnow().isoformat(),
    }

    if JINJA2_AVAILABLE and Template is not None:
        template = Template(REPORT_TEMPLATE)
        return template.render(**context)
    else:
        # Fallback: simple f-string rendering
        return _render_fallback(context)


def _render_fallback(ctx: Dict[str, Any]) -> str:
    """Fallback renderer when Jinja2 is not available."""
    lines = [
        f"# Penetration Test Report",
        f"",
        f"**Engagement:** {ctx['engagement_name']}",
        f"**Date:** {ctx['report_date']}",
        f"**Tester:** Chimeras Autonomous AI Pentest Swarm",
        f"",
        f"---",
        f"",
        f"## 1. Executive Summary",
        f"",
        f"{ctx['executive_summary']}",
        f"",
        f"---",
        f"",
        f"## 2. Scope",
        f"",
        f"**Mission Scope:** {ctx['mission_scope']}",
        f"**RoE:** {ctx.get('roe', 'N/A')}",
        f"",
        f"**Targets:**",
    ]
    for t in ctx["targets"]:
        lines.append(f"- {t}")
    lines.append(f"")
    lines.append(f"---")
    lines.append(f"")
    lines.append(f"## 3. Findings Summary")
    lines.append(f"")
    lines.append(f"| ID | Finding | Severity | CVSS | Status |")
    lines.append(f"|----|---------|----------|------|--------|")
    for f in ctx["findings"]:
        lines.append(f"| {f.get('id','')} | {f.get('title','')} | {f.get('severity','')} | {f.get('cvss','')} | {f.get('status','')} |")
    lines.append(f"")
    lines.append(f"---")
    lines.append(f"")
    for f in ctx["findings"]:
        lines.append(f"## {f.get('id','')}. {f.get('title','')}")
        lines.append(f"")
        lines.append(f"### Description")
        lines.append(f"{f.get('description','N/A')}")
        lines.append(f"")
        lines.append(f"### Risks")
        lines.append(f"{f.get('risks','N/A')}")
        lines.append(f"")
        lines.append(f"### Attack Vectors")
        lines.append(f"{f.get('attack_vectors','N/A')}")
        lines.append(f"")
        lines.append(f"### Proof of Concept")
        lines.append(f"{f.get('poc','N/A')}")
        lines.append(f"")
        lines.append(f"### Remediation")
        lines.append(f"{f.get('remediation','N/A')}")
        lines.append(f"")
        lines.append(f"---")
        lines.append(f"")
    lines.append(f"## 5. Critical Findings")
    lines.append(f"")
    if ctx["critical_findings"]:
        for cf in ctx["critical_findings"]:
            lines.append(f"- **[{cf.get('bot','').upper()}]** CVSS {cf.get('cvss','')} on {cf.get('target','')}: {cf.get('finding','')}")
    else:
        lines.append(f"*No critical findings (CVSS >= 7.0) recorded.*")
    lines.append(f"")
    lines.append(f"---")
    lines.append(f"")
    lines.append(f"*Report generated by Chimeras v2.3 — Cyberian Defenses*")
    return "\n".join(lines)